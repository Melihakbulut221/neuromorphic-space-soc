"""The Tiny Tapeout submission tree must not drift from hw/rtl.

tt/ is generated by scripts/gen_tt_submission.py: the RTL is copied out
of hw/rtl byte for byte, and the datasheet's register table is rendered
from sw/golden/regmap_gen.py. That only buys anything if the copy is
enforced, so this module checks the tree three independent ways:

  * every file listed in tt/MANIFEST.sha256 hashes to what the manifest
    says, and the manifest covers every generated file;
  * every RTL file in tt/src is byte-identical to hw/rtl, and nothing
    under tt/src is anything else;
  * re-running the generator in memory produces exactly the tree on
    disk (this is what catches a register-map edit, a pinout edit or a
    hand edit anywhere under tt/).

Plus a set of assertions about the submission itself, made against the
files on disk rather than against the generator, so that a bug in the
generator cannot make them vacuous: the tile shape, the top module, the
schema version, the fact that every declared source file exists, and
the pin contract -- names AND the wires under them, read out of the
wrapper's RTL rather than out of its header comment.

If this fails after an intentional change, the fix is:

    python3 scripts/gen_tt_submission.py

Nothing under tt/ is ever edited by hand.
"""

import hashlib
import importlib.util
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
TT = ROOT / "tt"
GENERATOR = ROOT / "scripts" / "gen_tt_submission.py"

# The pilot's Tiny Tapeout pin budget, fixed by the shuttle.
PIN_GROUPS = {"ui": 8, "uo": 8, "uio": 8}


def _load_generator():
    spec = importlib.util.spec_from_file_location("gen_tt_submission", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    sys.modules["gen_tt_submission"] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def gen():
    assert GENERATOR.is_file(), f"generator not found at {GENERATOR}"
    return _load_generator()


@pytest.fixture(scope="module")
def built(gen):
    """The tree as the generator would write it, {relpath: bytes}."""
    return gen.build()


@pytest.fixture(scope="module")
def info_yaml():
    yaml = pytest.importorskip("yaml")
    path = TT / "info.yaml"
    assert path.is_file(), "tt/info.yaml is missing; run the generator"
    return yaml.safe_load(path.read_text(encoding="utf-8"))


# ---------------------------------------------------------------------
# 1. the tree exists and matches its own manifest
# ---------------------------------------------------------------------
def test_submission_tree_exists():
    assert TT.is_dir(), (
        "tt/ does not exist. Run: python3 scripts/gen_tt_submission.py"
    )


def test_manifest_hashes_match_the_files():
    manifest = TT / "MANIFEST.sha256"
    assert manifest.is_file(), "tt/MANIFEST.sha256 is missing"
    bad = []
    for line in manifest.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        digest, rel = line.split("  ", 1)
        target = TT / rel
        if not target.is_file():
            bad.append(f"{rel}: listed in the manifest but not on disk")
            continue
        actual = hashlib.sha256(target.read_bytes()).hexdigest()
        if actual != digest:
            bad.append(f"{rel}: manifest {digest[:12]}, file {actual[:12]}")
    assert not bad, "tt/MANIFEST.sha256 disagrees with the tree:\n  " + "\n  ".join(bad)


def test_manifest_covers_every_generated_file(gen):
    manifest = TT / "MANIFEST.sha256"
    listed = {
        line.split("  ", 1)[1]
        for line in manifest.read_text(encoding="utf-8").splitlines()
        if line.strip()
    }
    missing = []
    for path in sorted(TT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(TT).as_posix()
        if rel == "MANIFEST.sha256" or not gen.is_generated(rel):
            continue
        if rel not in listed:
            missing.append(rel)
    assert not missing, (
        "files under tt/ that the manifest does not cover:\n  "
        + "\n  ".join(missing)
    )


# ---------------------------------------------------------------------
# 2. the RTL really is a copy
# ---------------------------------------------------------------------
def test_rtl_sources_are_byte_identical_to_hw_rtl(gen):
    mismatched = []
    for name in gen.RTL_SOURCES + gen.RTL_INCLUDES:
        source = ROOT / "hw" / "rtl" / name
        copy = TT / "src" / name
        assert source.is_file(), f"hw/rtl/{name} is missing"
        assert copy.is_file(), f"tt/src/{name} is missing; run the generator"
        if source.read_bytes() != copy.read_bytes():
            mismatched.append(name)
    assert not mismatched, (
        "tt/src has drifted from hw/rtl for: " + ", ".join(mismatched)
        + "\nRun: python3 scripts/gen_tt_submission.py"
    )


def test_every_source_under_src_is_a_copy(gen):
    """Nothing under tt/src is generated: every .v and .vh comes from hw/rtl.

    The submission used to carry one generated file, a name adapter that
    wrapped hw/rtl/tt_um_pilot.v in a shuttle-unique module name. The
    wrapper now carries that name itself, so the adapter is gone and this
    test holds the stronger property: what is hardened is exactly what is
    simulated in the source repository, with no extra hierarchy level.
    """
    expected = set(gen.RTL_SOURCES) | set(gen.RTL_INCLUDES)
    found = {
        p.name for p in (TT / "src").iterdir()
        if p.suffix in (".v", ".vh")
    }
    assert found == expected, (
        f"unexpected sources under tt/src: {sorted(found - expected)}; "
        f"missing: {sorted(expected - found)}"
    )
    assert not hasattr(gen, "ADAPTER_NAME"), (
        "the generator grew a name adapter again; the top module is "
        "supposed to be namespaced in hw/rtl itself"
    )


# ---------------------------------------------------------------------
# 3. regenerating produces exactly what is on disk
