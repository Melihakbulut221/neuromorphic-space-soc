def test_tree_matches_the_generator(gen, built):
    problems = gen.check(built, TT)
    assert not problems, (
        "the submission tree is out of date:\n  " + "\n  ".join(problems)
        + "\nRun: python3 scripts/gen_tt_submission.py"
    )


