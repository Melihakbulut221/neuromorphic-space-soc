def emit_rf(map_path, flops_path, out_path):
    m = json.load(open(map_path))
    flops = read_flops(flops_path)
    ent = {(e["stratum"], e["name"], e["bit"]): e for e in m["entries"]}

    def ref(key):
        e = ent.get(key)
        if e is None or e["gl"] is None:
            sys.exit("the register-file shadow needs %s and the mapping "
                     "has no flop for it" % (key,))
        r = verilog_ref(flops[e["gl"]]["q"])
        return ("~" + r) if e["pol"] else r

    lines = ["// GENERATED by hw/soc/fi/gl_map.py from %s -- do not edit."
             % os.path.basename(map_path),
             "// The register file's storage, the scrub pointer and the read",
             "// addresses, read out of the netlist by the mapped names, with",
             "// the storage polarity the trace found.",
             "  wire [991:0] fi_rf_data;",
             "  wire [216:0] fi_rf_chk;",
             "  wire [4:0]   fi_rf_ptr, fi_rf_ra, fi_rf_rb;"]
    for i in range(1, 32):
        for b in range(32):
            lines.append("  assign fi_rf_data[%d] = %s;"
                         % (32 * (i - 1) + b, ref(("regfile", "x%d" % i, b))))
        for b in range(7):
            lines.append("  assign fi_rf_chk[%d] = %s;"
                         % (7 * (i - 1) + b, ref(("regfile_ecc", "x%d_chk" % i, b))))
    for b in range(5):
        lines.append("  assign fi_rf_ptr[%d] = %s;"
                     % (b, ref(("regfile_ecc", "scrub_ptr", b))))
    # raddr_a = instr_rdata_id[19:15], raddr_b = instr_rdata_id[24:20]
    # (ibex_decoder: rf_raddr_a_o = instr[19:15], rf_raddr_b_o = instr[24:20])
    for b in range(5):
        lines.append("  assign fi_rf_ra[%d] = %s;"
                     % (b, ref(("if_id", "instr_rdata_id_o", 15 + b))))
        lines.append("  assign fi_rf_rb[%d] = %s;"
                     % (b, ref(("if_id", "instr_rdata_id_o", 20 + b))))
    lines.append("  fi_rf_shadow u_rf_shadow (")
    lines.append("      .clk_i (clk), .rst_ni (rst_n),")
    lines.append("      .data_i (fi_rf_data), .chk_i (fi_rf_chk), .ptr_i (fi_rf_ptr),")
    lines.append("      .raddr_a_i (fi_rf_ra), .raddr_b_i (fi_rf_rb),")
    lines.append("      .sec_cycles_o (rf_sec_cycles), .ded_cycles_o (rf_ded_cycles),")
    lines.append("      .sec_seen_o (rf_sec_seen), .ded_seen_o (rf_ded_seen));")
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit-rtl-trace", default=None)
    ap.add_argument("--rtl-trace", default=None)
    ap.add_argument("--gl-trace", default=None)
    ap.add_argument("--flops", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--report", default=None)
    ap.add_argument("--alias", default=None,
                    help="fi_alias.json from hw/soc/flow/fi_gl_alias.sh")
    ap.add_argument("--emit-rf", nargs=3, default=None,
                    metavar=("MAP", "FLOPS", "VH"))
    args = ap.parse_args()
    if args.emit_rtl_trace:
        emit_rtl_trace(args.emit_rtl_trace)
        return
    if args.emit_rf:
        emit_rf(*args.emit_rf)
        return
    flops = read_flops(args.flops)
    rtl_cols, n_rtl = read_trace(args.rtl_trace)
    gl_cols, n_gl = read_trace(args.gl_trace)
    shift, rtl_cols, gl_cols, n = align(rtl_cols, gl_cols, flops)
    aliases = load_aliases(args.alias) if args.alias else None
    entries, used, _ = derive(rtl_cols, gl_cols, flops, aliases)
    out = {"cycles": n, "rtl_rows": n_rtl, "gl_rows": n_gl,
           "gl_row_shift": shift,
           "cycle_rule": "gl_cycle = rtl_cycle + (%d)" % shift,
           "rtl_bits": len(entries), "gl_flops": len(flops),
           "entries": entries}
    with open(args.out, "w") as fh:
        json.dump(out, fh, indent=1)
    lines = []

    def say(s):
        print(s)
        lines.append(s)
    say("clean run: RTL %d rows, gate level %d rows; aligned on %d rows "
        "with the gate-level row shifted by %d (gate-level row t is RTL "
        "row t - (%d)); a record's cycle is replayed as gl_cycle = "
        "rtl_cycle + (%d)" % (n_rtl, n_gl, n, shift, shift, shift))
    report(entries, used, flops, gl_cols, rtl_cols, say)
    if args.report:
        with open(args.report, "w") as fh:
            fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
