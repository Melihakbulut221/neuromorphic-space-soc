def derive(rtl_cols, gl_cols, flops, aliases=None):
    layout, width = site_layout()
    if len(rtl_cols) != width:
        sys.exit("RTL trace is %d bits wide, targets.py says %d"
                 % (len(rtl_cols), width))
    if len(gl_cols) != len(flops):
        sys.exit("gate-level trace is %d bits wide, flops.tsv lists %d"
                 % (len(gl_cols), len(flops)))

    by_trace = collections.defaultdict(list)
    for f in flops:
        by_trace[gl_cols[f["idx"]]].append(f["idx"])
    by_name = {plain(f["q"]): f["idx"] for f in flops}

    entries = []
    used = collections.Counter()
    for k, s, off in layout:
        for b in range(s.width):
            col = rtl_cols[off + b]
            name_key = ("u_ibex." + s.path, b if s.width > 1 else None)
            name_idx = by_name.get(name_key)
            if name_idx is None:
                name_idx = by_name.get(("u_ibex." + s.path, b))
            const = col.count(col[0]) == len(col)
            same = by_trace.get(col, [])
            inv = by_trace.get(complement(col), [])
            cands = [(i, 0) for i in same] + [(i, 1) for i in inv]
            al_idx, al_names = alias_candidates(aliases, s.path, b, by_name)
            if name_idx is not None and name_idx not in al_idx:
                al_idx = [name_idx] + al_idx
            e = {"site": k, "stratum": s.stratum, "name": s.name,
                 "path": s.path, "bit": b, "rtl_flat": off + b,
                 "constant": const, "candidates": cands,
                 "aliases": al_idx,
                 "name_idx": name_idx, "gl": None, "pol": 0, "how": "none"}
            # The decision, in order of how much it rests on:
            #   trace+name   one flop by trace, and it carries the RTL's
            #                own name or one of its aliases
            #   trace        one flop by trace, no name agrees
            #   trace&alias  several by trace, exactly one is an alias
            #   alias        the trace says nothing (constant over the
            #                run) and exactly one flop carries an alias
            #   ambiguous    several by trace, none or several by alias
            #   constant     constant over the run and no alias survives
            #   none         a live bit with no trace twin at all
            trace_named = [(i, p) for i, p in cands if i in al_idx]
            if const:
                # A name-only mapping is still checked against the trace
                # it has: the RTL bit is constant, so the flop under the
                # alias must be constant at the same value (or, stored
                # inverted, at the other).  A flop that toggles under an
                # RTL register's name is a re-encoded register that kept
                # the name -- yosys's fsm pass on ctrl_fsm_cs did exactly
                # that -- and it is not the RTL bit.  Control 5 of
                # gl_campaign.py is what found this.
                if len(al_idx) == 1:
                    gcol = gl_cols[al_idx[0]]
                    if gcol == col:
                        e.update(gl=al_idx[0], pol=0, how="alias")
                    elif gcol == complement(col):
                        e.update(gl=al_idx[0], pol=1, how="alias")
                    else:
                        e["how"] = "alias(withdrawn)"
                        e["withdrawn_idx"] = al_idx[0]
                elif len(al_idx) > 1:
                    e["how"] = "ambiguous"
                else:
                    e["how"] = "constant"
            elif not cands:
                e["how"] = "none"
            elif len(cands) == 1:
                i, p = cands[0]
                e.update(gl=i, pol=p,
                         how="trace+name" if i in al_idx else "trace")
            elif len(trace_named) == 1:
                i, p = trace_named[0]
                e.update(gl=i, pol=p, how="trace&alias")
            else:
                e["how"] = "ambiguous"
            # A trace-only identification of a bit that barely moves is
            # a coincidence waiting to happen: 5,873 flops, and a bit
            # that toggles twice has few distinct traces to be equal to.
            # Sixteen transitions or an agreeing alias, or it is not
            # injected.
            if e["how"] == "trace":
                e["transitions"] = sum(1 for t in range(1, len(col))
                                       if col[t] != col[t - 1])
                if e["transitions"] < 16:
                    e.update(gl=None, how="trace(weak)")
            # Removed by synthesis before mapping: the RTL census has no
            # flip-flop for it.  Whatever the trace matched is another
            # register's flop, and the RTL record measured nothing
            # physical (docs/42 section 4.4 item 1).
            e["in_rtl_census"] = rtl_census_has(aliases, s.path, b)
            if e["in_rtl_census"] is False and e["gl"] is not None:
                e.update(deleted_twin=e["gl"], gl=None, how="deleted")
            elif e["in_rtl_census"] is False:
                e["how"] = "deleted"
            if e["gl"] is not None:
                used[e["gl"]] += 1
            entries.append(e)
    # Merged: two live RTL registers that synthesis stored in ONE flop
    # (opt_merge: same D, same reset, same enable -- Ibex's duplicated
    # instruction register, ibex_top's multi-bit busy encoding).  An
    # upset in that flop is an upset in both RTL registers at once, so
    # the record is replayed but is not like-for-like, and the report
    # keeps it apart.
    for e in entries:
        if e["gl"] is not None and used[e["gl"]] > 1:
            e["merged_with"] = [x["stratum"] + "." + x["name"] + "[%d]" % x["bit"]
                                for x in entries
                                if x["gl"] == e["gl"] and x is not e]
            e["how"] = "merged"
    return entries, used, by_trace


def align(rtl_cols, gl_cols, flops):
    """The two benches release reset at the same clock edge, but the RTL
    flops evaluate that edge before the bench's reset assignment and the
    netlist's flops -- behind a clock tree of buffer cells -- after it,
    so the netlist leaves reset one clock earlier than the RTL and its
    trace is one row ahead.  This does not assume that: it measures the
    shift on every register-file data bit that toggles, over -2..+2 rows,
    and refuses to map unless exactly one shift makes every one of them
    identical.  The same shift is what the campaign applies to a
    replayed cycle."""
    by_name = {plain(f["q"]): f["idx"] for f in flops}
    layout, _ = site_layout()
    probes = []
    for k, s, off in layout:
        if s.stratum != "regfile":
            continue
        for b in range(s.width):
            gi = by_name.get(("u_ibex." + s.path, b))
            if gi is None:
                continue
            col = rtl_cols[off + b]
            if col.count(col[0]) != len(col):
                probes.append((off + b, gi))
    if len(probes) < 100:
        sys.exit("only %d register-file bits toggle in the clean run and "
                 "carry their name; not enough to align" % len(probes))
    good = []
    for sh in (-2, -1, 0, 1, 2):
        ok = 0
        for r, g in probes:
            a = rtl_cols[r]
            bcol = gl_cols[g]
            if sh >= 0:
                a2, b2 = a[:len(a) - sh] if sh else a, bcol[sh:]
            else:
                a2, b2 = a[-sh:], bcol[:len(bcol) + sh]
            n = min(len(a2), len(b2))
            if a2[:n] == b2[:n]:
                ok += 1
        if ok == len(probes):
            good.append(sh)
    if len(good) != 1:
        sys.exit("the traces align at %s (of -2..2) on %d probe bits; "
                 "exactly one shift is required" % (good, len(probes)))
    sh = good[0]
    # gate-level row t corresponds to RTL row t - sh
    if sh >= 0:
        rtl2 = [c[:len(c) - sh] if sh else c for c in rtl_cols]
        gl2 = [c[sh:] for c in gl_cols]
    else:
        rtl2 = [c[-sh:] for c in rtl_cols]
        gl2 = [c[:len(c) + sh] for c in gl_cols]
    n = min(len(rtl2[0]), len(gl2[0]))
    rtl2 = [c[:n] for c in rtl2]
    gl2 = [c[:n] for c in gl2]
    return sh, rtl2, gl2, n


def report(entries, used, flops, gl_cols, rtl_cols, say):
    how = collections.Counter(e["how"] for e in entries)
    say("RTL site bits: %d" % len(entries))
    for h in ("trace+name", "trace", "trace&alias", "alias", "merged",
              "ambiguous", "constant", "trace(weak)", "alias(withdrawn)",
              "deleted", "none"):
        say("  %-18s %d" % (h, how.get(h, 0)))
    inv = sum(1 for e in entries if e["gl"] is not None and e["pol"])
    say("  mapped with inverted storage polarity: %d" % inv)
    multi = [(i, n) for i, n in used.items() if n > 1]
    say("  netlist flops that are the twin of more than one RTL bit: %d"
        % len(multi))
    say("")
    say("per stratum: bits / mapped / of which by trace alone / unmapped")
    per = collections.defaultdict(lambda: [0, 0, 0, 0])
    for e in entries:
        d = per[e["stratum"]]
        d[0] += 1
        if e["gl"] is not None:
            d[1] += 1
            if e["how"] in ("trace", "trace&alias"):
                d[2] += 1
        else:
            d[3] += 1
    for st in targets.STRATA:
        d = per[st]
        say("  %-12s %5d %5d %5d %5d" % (st, d[0], d[1], d[2], d[3]))
    say("")
    say("unmapped RTL bits, by site:")
    grp = collections.defaultdict(list)
    for e in entries:
        if e["gl"] is None:
            grp[(e["stratum"], e["name"], e["how"])].append(e["bit"])
    for (st, name, h), bits in sorted(grp.items()):
        say("  %-12s %-26s %-10s %d bit(s): %s"
            % (st, name, h, len(bits), _ranges(bits)))
    say("")
    say("RTL bits that share a netlist flop with another live RTL bit (merged):")
    seen = set()
    for e in entries:
        if e["how"] == "merged" and e["gl"] not in seen:
            seen.add(e["gl"])
            say("  #%-5d %-70s <- %s.%s[%d], %s" % (
                e["gl"], flops[e["gl"]]["q"], e["stratum"], e["name"], e["bit"],
                ", ".join(e["merged_with"])))
    say("")
    say("RTL bits removed by synthesis (no flip-flop in the RTL census):")
    grp = collections.defaultdict(list)
    for e in entries:
        if e["how"] == "deleted":
            grp[(e["stratum"], e["name"])].append(e["bit"])
    for (st, name), bits in sorted(grp.items()):
        say("  %-12s %-26s %d bit(s): %s" % (st, name, len(bits), _ranges(bits)))
    say("")
    say("RTL bits whose alias-named flop toggles while the RTL bit is constant (withdrawn):")
    for e in entries:
        if e["how"] == "alias(withdrawn)":
            say("  %-12s %-26s[%2d] alias flop #%-5d %s" % (
                e["stratum"], e["name"], e["bit"], e["withdrawn_idx"],
                flops[e["withdrawn_idx"]]["q"]))
    say("")
    say("RTL bits mapped by trace to a flop of ANOTHER name (no alias agrees):")
    for e in entries:
        if e["how"] == "trace":
            say("  %-12s %-26s[%2d] -> #%-5d %s%s"
                % (e["stratum"], e["name"], e["bit"], e["gl"],
                   flops[e["gl"]]["q"], "  (inverted)" if e["pol"] else ""))
    say("")
    # the other direction
    core = [f for f in flops if plain(f["q"])[0].startswith("u_ibex.")]
    twins = set(e["gl"] for e in entries if e["gl"] is not None)
    rtl_by_trace = collections.defaultdict(list)
    for e in entries:
        rtl_by_trace[rtl_cols[e["rtl_flat"]]].append(e)
    say("netlist flip-flops under u_ibex.: %d; twins of an RTL bit: %d; "
        "not: %d" % (len(core), sum(1 for f in core if f["idx"] in twins),
                     sum(1 for f in core if f["idx"] not in twins)))
    say("  of those not: constant over the clean run / trace-equal to some "
        "RTL bit (a duplicate) / trace-equal to nothing in the RTL site table")
    cconst = cdup = cnew = 0
    newnames = collections.Counter()
    dupnames = collections.Counter()
    for f in core:
        if f["idx"] in twins:
            continue
        col = gl_cols[f["idx"]]
        if col.count(col[0]) == len(col):
            cconst += 1
        elif col in rtl_by_trace or complement(col) in rtl_by_trace:
            cdup += 1
            dupnames[plain(f["q"])[0]] += 1
        else:
            cnew += 1
            newnames[plain(f["q"])[0]] += 1
    say("  %d / %d / %d" % (cconst, cdup, cnew))
    say("  duplicates, by name:")
    for n, c in sorted(dupnames.items()):
        say("    %-72s %d" % (n, c))
    say("  trace-equal to nothing in the site table, by name:")
    for n, c in sorted(newnames.items()):
        say("    %-72s %d" % (n, c))


def _ranges(bits):
    bits = sorted(bits)
    out = []
    start = prev = bits[0]
    for b in bits[1:]:
        if b == prev + 1:
            prev = b
            continue
        out.append("%d" % start if start == prev else "%d-%d" % (start, prev))
        start = prev = b
    out.append("%d" % start if start == prev else "%d-%d" % (start, prev))
    return ",".join(out)


def read_flops(path):
    out = []
    with open(path) as fh:
        hdr = fh.readline().rstrip("\n").split("\t")
        for line in fh:
            row = dict(zip(hdr, line.rstrip("\n").split("\t")))
            row["idx"] = int(row["idx"])
            out.append(row)
    return out


