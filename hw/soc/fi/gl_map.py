def site_layout():
    """(site index, site, offset) with the flat bit of site k bit b at
    offset_k + b."""
    out = []
    off = 0
    for k, s in enumerate(targets.SITES):
        out.append((k, s, off))
        off += s.width
    return out, off


def emit_rtl_trace(path):
    layout, width = site_layout()
    lines = []
    lines.append("// GENERATED by hw/soc/fi/gl_map.py -- do not edit.")
    lines.append("// A second elaboration root that traces every campaign site of")
    lines.append("// tb_soc_fi.v's design per cycle. %d bits, %d sites."
                 % (width, len(layout)))
    lines.append("`timescale 1ns / 1ps")
    lines.append("module fi_rtl_trace;")
    lines.append("  wire [%d:0] v = {" % (width - 1))
    for k, s, off in reversed(layout):
        lines.append("    tb_soc_fi.dut.u_ibex.%s%s" % (s.path, "," if k else ""))
    lines.append("  };")
    lines.append("  reg [1023:0] f;")
    lines.append("  integer fd = 0;")
    lines.append("  initial if ($value$plusargs(\"trace=%s\", f)) fd = $fopen(f, \"w\");")
    lines.append("  always @(negedge tb_soc_fi.clk)")
    lines.append("    if (tb_soc_fi.rst_n && fd) $fwrite(fd, \"%b\\n\", v);")
    lines.append("endmodule")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


# ---------------------------------------------------------------------
# reading traces
# ---------------------------------------------------------------------
def read_trace(path):
    """Rows of '0'/'1'/'x' text, MSB first as Verilog prints them; returns
    a list of per-bit column strings indexed by bit number (bit 0 is
    the LAST character of a row)."""
    rows = [line.rstrip("\n") for line in open(path) if line.strip()]
    width = len(rows[0])
    for r in rows:
        if len(r) != width:
            sys.exit("ragged trace %s" % path)
    # transpose: column j (from the right) is bit j
    cols = ["".join(r[width - 1 - j] for r in rows) for j in range(width)]
    return cols, len(rows)


def complement(col):
    return col.translate(str.maketrans("01", "10"))


# ---------------------------------------------------------------------
# the aliases, from hw/soc/flow/fi_gl_alias.sh's JSON
# ---------------------------------------------------------------------
_GENBLK = __import__("re").compile(r"(^|\.)genblk\d+\.")


def _norm(name):
    """Yosys puts an anonymous generate scope (`genblk3`) in the
    multiplier's path where Icarus does not; hw/soc/fi/coverage.py
    normalises it the same way."""
    return _GENBLK.sub(r"\1", name)


def load_aliases(path):
    """RTL site path (Icarus form, relative to ibex_top) and bit ->
    the set of (name, bit) every public wire on that net carries in the
    elaborated, flattened, un-renamed design, each prefixed `u_ibex.`
    so it can be looked up among the netlist's Q nets."""
    j = json.load(open(path))
    mod = j["modules"]["ibex_top"]
    nn = mod["netnames"]
    by_bit = collections.defaultdict(set)
    named = {}
    for name, d in nn.items():
        if d.get("hide_name"):
            continue
        for i, b in enumerate(d["bits"]):
            if isinstance(b, str):
                continue           # a constant
            by_bit[b].add((name, i))
            named[(_norm(name), i)] = b
    # The RTL census: every bit a flip-flop cell drives after opt_clean.
    # A site bit that is not in this set is one synthesis removed before
    # it ever reached a technology cell -- docs/42 section 4.2's three
    # IF-stage registers and its one mcountinhibit bit, and whatever
    # else the parameters make constant.  fi_coverage.sh counts the same
    # set; this reads it from the same elaboration's JSON.
    ff = set()
    for cell in mod["cells"].values():
        if cell["type"] in ("$dff", "$adff", "$dffe", "$adffe", "$sdff",
                            "$sdffe", "$sdffce", "$dffsr", "$dffsre",
                            "$adlatch", "$dlatch"):
            for b in cell["connections"].get("Q", []):
                if not isinstance(b, str):
                    ff.add(b)
    return by_bit, named, ff


def rtl_census_has(aliases, path, bit):
    """Whether the RTL bit is stored by a flip-flop after the RTL
    census's own opt_clean; None when no alias JSON was given."""
    if aliases is None:
        return None
    by_bit, named, ff = aliases
    b = named.get((path, bit))
    return b is not None and b in ff


def alias_candidates(aliases, path, bit, by_name):
    """Netlist flop indices whose Q-net name is an alias of the RTL
    bit, and the alias names themselves."""
    if aliases is None:
        return [], set()
    by_bit, named, ff = aliases
    b = named.get((path, bit))
    if b is None:
        return [], set()
    names = set()
    idxs = set()
    for name, i in by_bit[b]:
        names.add(("u_ibex." + name, i))
        for key in (("u_ibex." + name, i), ("u_ibex." + name, None)):
            if key in by_name:
                idxs.add(by_name[key])
    return sorted(idxs), names


