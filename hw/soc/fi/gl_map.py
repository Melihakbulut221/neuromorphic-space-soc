#!/usr/bin/env python3
"""Which netlist flip-flop is which RTL bit, derived from a trace of
both designs on the clean run -- docs/74.

    gl_map.py --emit-rtl-trace <fi_rtl_trace.v>
    gl_map.py --rtl-trace <rtl.trace> --gl-trace <gl.trace> \\
              --flops <flops.tsv> --out <map.json> [--report <map.txt>]
    gl_map.py --emit-rf <map.json> <flops.tsv> <fi_gl_rf.vh>

WHY A TRACE AND NOT A NAME

docs/32 section 4.2 found that a flip-flop's name in the netlist is
whichever alias yosys kept: a rail carried its consumer's name, and a
bit that had been `_0255_` in one harden was `_0253_` in the next. On
this netlist the IF/ID instruction register's bits 19:15 are named after
the register file's read-address port, the fetch address is named after
`crash_dump_o`, and three controller registers have no name at all
(hw/soc/out/gl74/census_by_name.txt). A name is a hypothesis about
which flip-flop this is. The trace is the measurement.

THE MEASUREMENT

Both benches run the clean workload with nothing injected and write,
on every falling clock edge, the value of every register: the RTL bench
its 2,451 site bits (through the second root this module generates,
hw/soc/flow/fi_core.sh's FI_EXTRA_ROOT), the gate-level bench its
5,873 flip-flops (tb_soc_fi_gl.v's +trace). Two bits that are the same
storage have the same trace, cycle for cycle, for 18,682 cycles; a
netlist flip-flop that stores the complement has the complemented
trace. So an RTL bit maps to the netlist flip-flops whose trace equals
its own or its complement, and the census then says, for every RTL
bit, whether it has exactly one twin, several (a duplicate), or none
(deleted or re-encoded), and for every netlist flip-flop under
`u_ibex.` whether it is some RTL bit's twin or something synthesis
made.

WHAT A TRACE CANNOT DECIDE

Two registers that hold the same value throughout the clean run have
the same trace and cannot be told apart by it: a bit that is constant
over the run, or two bits that happen to agree on every cycle of this
workload. The mapping therefore prefers, among trace-equal candidates,
the one whose netlist name matches the RTL path, and marks every
mapping with how it was decided -- `trace+name`, `trace` (unique by
trace, name differs), `ambiguous` (several by trace, none by name;
NOT injected), `constant` (the RTL bit never changes in the clean run,
so the trace says nothing; mapped by name only if a same-named flop
exists, else not injected), and `none`. The campaign injects only
through `trace+name` and `trace`, and docs/74 reports the others.
"""

